// A string module needs no CSS step in the host's bundler; it is injected into the shadow root at runtime.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = path.resolve(root, ".tailwind/theme.css");
const output = path.resolve(root, "src/ui/generatedStyles.ts");

const css = readFileSync(input, "utf-8");

mkdirSync(path.dirname(output), { recursive: true });
writeFileSync(
  output,
  `// GENERATED by scripts/cssToTs.mjs from src/ui/theme.css - do not edit.\n` +
    `// Regenerate with \`npm run build:css\` (runs as part of \`npm run build\`).\n` +
    `// Committed like dist/ is: the package ships built, and a consumer must never need a CSS build step.\n` +
    `export const PLUGIN_STYLES = ${JSON.stringify(css)}\n`,
  "utf-8"
);

console.log(`[cssToTs] ${css.length.toLocaleString()} chars -> src/ui/generatedStyles.ts`);
